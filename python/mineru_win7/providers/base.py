"""Protocol seam: submit accepts only a host-authorized binary snapshot."""
from typing import Any, Dict, Protocol


class MinerUProvider(Protocol):
    async def health(self, signal=None) -> Dict[str, Any]: ...
    async def submit(self, snapshot, options, signal=None) -> Dict[str, Any]: ...
    async def status(self, task_id: str, signal=None) -> Dict[str, Any]: ...
    async def result(self, task_id: str, signal=None): ...
    def close(self) -> None: ...
